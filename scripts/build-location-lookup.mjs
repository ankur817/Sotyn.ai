/**
 * Generates src/data/locations/lookup.js from the district registry.
 *
 * The serverless intake needs to check a state/district pair without importing
 * a large JSON file, so this emits a plain JS module with just the identity
 * fields: "state-slug/district-slug" -> { state_code, district_code, names }.
 * Run after any registry change:  npm run locations
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const SRC = new URL("../src/data/locations/districts.json", import.meta.url);
const OUT = new URL("../src/data/locations/lookup.js", import.meta.url);

if (!existsSync(SRC)) {
  console.error("No districts.json yet — nothing to generate.");
  process.exit(1);
}
const registry = JSON.parse(readFileSync(SRC, "utf8"));
const entries = [];
for (const s of registry.states || []) {
  for (const d of s.districts || []) {
    entries.push([
      `${s.state_slug}/${d.district_slug}`,
      { s: s.state_code, d: d.district_code, sn: s.state_name, dn: d.district_name },
    ]);
  }
}
entries.sort((a, b) => a[0].localeCompare(b[0]));

const body = `/* GENERATED by scripts/build-location-lookup.mjs - do not edit.
 * Source snapshot: ${registry.snapshot?.primary_source || "unknown"} (retrieved ${registry.snapshot?.retrieved || "unknown"}).
 * ${entries.length} districts across ${(registry.states || []).length} states/UTs.
 */
export const LOCATIONS = ${JSON.stringify(Object.fromEntries(entries))};

/** Returns the registry record for a state/district pair, or null. Never echoes caller text. */
export function lookupLocation(stateSlug, districtSlug) {
  const key = \`\${String(stateSlug || "").toLowerCase()}/\${String(districtSlug || "").toLowerCase()}\`;
  if (!/^[a-z0-9-]{1,60}\\/[a-z0-9-]{1,60}$/.test(key)) return null;
  const hit = LOCATIONS[key];
  return hit ? { state_code: hit.s, district_code: hit.d, state_name: hit.sn, district_name: hit.dn } : null;
}
`;
writeFileSync(OUT, body);
console.log(`lookup.js: ${entries.length} districts, ${(registry.states || []).length} states/UTs`);
